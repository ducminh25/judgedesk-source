// Importing the shared harness also registers its existing single-run gate.
// Explicit opt-in is mandatory: no fixture is launched on other hosts or during
// the ordinary server suite. No destructive reproduction is executed implicitly.
// Focused invocation must select --test-name-pattern='macOS interactive lifecycle'
// so the registered single-run gate is not also executed. Set
// JUDGEDESK_INTERACTIVE_LIFECYCLE_CASES=harmless for the first caller check; omit
// it for the full paired suite once an owned-pin teardown has been verified.
// Use guardian-both to focus the concurrent two-guardian failure reproduction.
// Use resources for the independent resource/verdict and repeated-cancel matrix.
interface ResourceCase {
  name: string;
  args: readonly string[];
  peerArgs: readonly string[];
  reason: ExecutorRunReason;
  submissionVerdict: string;
  interactorVerdict: string;
  outputBytes?: number;
  wallTimeMs?: number;
  memoryBytes?: number;
  exitCode?: number | null;
}

// Quota rows exercise both a blocked destination and successful reuse of more
// than the relay's 64 KiB capacity. All generated bytes remain in owned pipes.
const RESOURCE_CASES: readonly ResourceCase[] = [
  { name: "output quota against a nonreading peer", args: ["output-bytes", "1048576"],
    peerArgs: ["sleep-ms", "5000"], outputBytes: 8 * 1024,
    reason: "output_limit", submissionVerdict: "OLE", interactorVerdict: "JE" },
  { name: "output quota after relay backpressure drains", args: ["output-bytes", "1048576"],
    peerArgs: ["drain-input"], outputBytes: 96 * 1024,
    reason: "output_limit", submissionVerdict: "OLE", interactorVerdict: "JE" },
  { name: "wall deadline", args: ["sleep-ms", "5000"], peerArgs: ["sleep-ms", "5000"],
    wallTimeMs: 400, reason: "wall_time_limit", submissionVerdict: "TLE", interactorVerdict: "JE" },
  { name: "memory quota", args: ["allocate-mib", "32", "5000"], peerArgs: ["sleep-ms", "5000"],
    memoryBytes: 16 * 1024 * 1024, reason: "memory_limit", submissionVerdict: "MLE", interactorVerdict: "JE" },
  { name: "clean exit", args: ["sleep-ms", "10"], peerArgs: ["delayed-exit", "0"],
    reason: "exited", exitCode: 0, submissionVerdict: "AC", interactorVerdict: "AC" },
  { name: "nonzero exit", args: ["exit-code", "1"], peerArgs: ["sleep-ms", "5000"],
    reason: "exited", exitCode: 1, submissionVerdict: "JE", interactorVerdict: "WA" },
  { name: "signal crash", args: ["signal-crash"], peerArgs: ["sleep-ms", "5000"],
    reason: "exited", exitCode: null, submissionVerdict: "JE", interactorVerdict: "JE" },
];

test("macOS interactive lifecycle fault gate configuration", { timeout: 240_000 }, async (t) => {
  if (process.env.JUDGEDESK_RUN_GUARDIAN_FAULT_GATE !== "1") {
    t.diagnostic("Lifecycle faults require JUDGEDESK_RUN_GUARDIAN_FAULT_GATE=1 on Apple Silicon.");
    return;
  }
  assert.equal(process.platform, "darwin");
  assert.equal(process.arch, "arm64");
  const caseSelection = process.env.JUDGEDESK_INTERACTIVE_LIFECYCLE_CASES;
  assert.ok(caseSelection === undefined || ["harmless", "guardian-both", "resources"].includes(caseSelection),
    "JUDGEDESK_INTERACTIVE_LIFECYCLE_CASES must be unset, harmless, guardian-both, or resources");

  if (caseSelection !== "harmless" && caseSelection !== "resources") {
    const guardianCases = ([[0], [1], [0, 1]] as const)
      .filter((sides) => caseSelection !== "guardian-both" || sides.length === 2);
    for (const killedSides of guardianCases) {
      await t.test(`guardian loss on participant ${killedSides.join(" and ")} drains the pair and preserves a sentinel`, async () => {
        await withGateRuntime(async (runtime) => {
          const pair = preparePair(runtime, "exchange-and-hold");
          const sentinelId = gateId("sentinel");
          const sentinel = observed(startLongRun(runtime, sentinelId));
          const sentinelGo = await waitForTrace(runtime, sentinelId, "target_started");
          const sentinelAnchor = requireIdentity(sentinelGo, "anchor");
          const sentinelTarget = requireIdentity(sentinelGo, "target");
          const pending = observed(startPair(runtime, pair));
          const enrolled = await releasedPair(runtime, pair);
          assert.equal(await generationExclusiveAvailable(runtime.generationPath), false);

          for (const side of killedSides) {
            const guardian = requireIdentity(enrolled[side], "guardian");
            // Signal only the authenticated guardian which is still this executor's
            // direct child. Never signal a traced target or a numeric process group.
            assertExactGuardianCommand(guardian.pid);
            assertKernelIdentity(guardian);
            assert.equal(parentPid(guardian.pid), runtime.harness.pid);
            process.kill(guardian.pid, "SIGKILL");
          }
          for (const side of killedSides) {
            await waitForProcessGone(requireIdentity(enrolled[side], "guardian").pid, 5_000);
          }

          const cancelled = await bounded(cancelRun(runtime, pair.runId), 8_000,
            "pair cancellation remained blocked after authenticated guardian loss");
          // A fault may finish cleanup before this cancel request is processed;
          // either acknowledgement still requires the terminal proof below.
          assert.equal(typeof cancelled, "boolean");
          const outcome = await bounded(pending, 8_000,
            "interactive ownership never settled after guardian loss");
          assert.ok("value" in outcome, "error" in outcome ? String(outcome.error) : undefined);
          assert.equal(outcome.value.runId, pair.runId);
          for (const result of [outcome.value.submissionResult, outcome.value.interactorResult]) {
            assert.ok(["cancelled", "internal_error"].includes(result.reason), JSON.stringify(result));
          }
          await provePairDrained(runtime, pair, enrolled);
          assertKernelIdentity(sentinelAnchor);
          assertKernelIdentity(sentinelTarget);
          assertGroupContains(sentinelAnchor);
          assert.equal(await generationExclusiveAvailable(runtime.generationPath), false);

          assert.equal(await cancelRun(runtime, sentinelId), true);
          const sentinelOutcome = await sentinel;
          assert.ok("value" in sentinelOutcome,
            "error" in sentinelOutcome ? String(sentinelOutcome.error) : undefined);
          assert.equal(sentinelOutcome.value.reason, "cancelled");
          await waitForTrace(runtime, sentinelId, "group_drained");
          await assertGroupEmpty(sentinelAnchor.pgid);
          assertNoRunProfileArtifacts(runtime, sentinelId);
          await runtime.harness.shutdown();
          await waitForGenerationExclusive(runtime.generationPath, 5_000);
        });
      });
    }

    if (caseSelection !== "guardian-both") {
      await t.test("executor SIGKILL drains both released participants before releasing the generation", async () => {
        await withGateRuntime(async (runtime) => {
          const pair = preparePair(runtime, "exchange-and-hold");
          const pending = observed(startPair(runtime, pair));
          const enrolled = await releasedPair(runtime, pair);
          assert.equal(await generationExclusiveAvailable(runtime.generationPath), false);

          // forceStop signals the actual spawned executor ChildProcess. No traced
          // numeric PID/PGID is used as replacement authority to kill the executor.
          await runtime.harness.forceStop();
          await runtime.harness.waitForExit(5_000);
          assert.equal(runtime.harness.child.signalCode, "SIGKILL");
          const outcome = await bounded(pending, 1_000,
            "executor death left the interactive request pending");
          assert.ok("error" in outcome, "SIGKILL returned a premature successful pair result");
          assert.match(String(outcome.error), /Native executor exited|control pipe/i);

          // Observe kernel group emptiness independently of the fault trace before
          // checking the guardians' drain acknowledgements or releasing the lease.
          await Promise.all(enrolled.map((event) =>
            assertGroupEmpty(requireIdentity(event, "anchor").pgid)));
          await provePairDrained(runtime, pair, enrolled);
          for (const event of enrolled) {
            const guardian = requireIdentity(event, "guardian");
            await waitForTrace(runtime, event.runId, "guardian_cleaned", 5_000);
            await waitForProcessGone(guardian.pid, 5_000);
          }
          await waitForGenerationExclusive(runtime.generationPath, 5_000);
          assert.equal(runtime.harness.child.stdin.destroyed, true);
          assert.equal(runtime.harness.child.stdout.readableEnded, true);
          assert.equal(runtime.harness.child.stderr.readableEnded, true);
        });
      });

      await t.test("executor control EOF drains both released participants before releasing the generation", async () => {
        await withGateRuntime(async (runtime) => {
          const pair = preparePair(runtime, "exchange-and-hold");
          const pending = observed(startPair(runtime, pair));
          const enrolled = await releasedPair(runtime, pair);
          assert.equal(await generationExclusiveAvailable(runtime.generationPath), false);
          runtime.harness.child.stdin.end();
          await runtime.harness.waitForExit(8_000);
          const outcome = await bounded(pending, 1_000, "EOF left the interactive request pending");
          if ("value" in outcome) {
            for (const result of [outcome.value.submissionResult, outcome.value.interactorResult]) {
              assert.ok(["cancelled", "internal_error"].includes(result.reason), JSON.stringify(result));
            }
          } else {
            assert.match(String(outcome.error), /Native executor exited|control pipe/i);
          }
          await provePairDrained(runtime, pair, enrolled);
          await waitForGenerationExclusive(runtime.generationPath, 5_000);
        });
      });
    }
  }

  if (caseSelection === undefined) {
    await t.test("missing second executable fails pair admission without enrolling either group", async () => {
      await withGateRuntime(async (runtime) => {
        const pair = preparePair(runtime, "normal-exchange");
        pair.interactor.executableId = `artifacts/${gateId("missing_interactor")}`;
        assert.equal(fs.existsSync(path.join(runtime.executorRoot, pair.interactor.executableId)), false);
        const result = await bounded(startPair(runtime, pair), 5_000,
          "missing interactor executable failed to settle at admission");
        for (const participant of [result.submissionResult, result.interactorResult]) {
          assert.equal(participant.reason, "internal_error", JSON.stringify(result));
          assert.equal(participant.exitCode, null, JSON.stringify(result));
        }
        assert.match(result.message ?? "", /unavailable|No such file|not found/i);
        for (const runId of [pair.runId, pair.submission.runId, pair.interactor.runId]) {
          assert.deepEqual(traceEvents(runtime.eventLog, runId), [],
            `missing executable enrolled or released an interactive process for ${runId}`);
          assertNoRunProfileArtifacts(runtime, runId);
        }
        const spools = fs.readdirSync(path.join(runtime.executorRoot, "profiles"))
          .filter((name) => name.startsWith(`${pair.runId}_`) && name.endsWith(".interactive"));
        assert.deepEqual(spools, [], "admission failure retained an interactive spool");
        await runtime.harness.shutdown();
        await waitForGenerationExclusive(runtime.generationPath, 5_000);
      });
    });
  }

  if (caseSelection === undefined || caseSelection === "harmless") {
    for (const mode of ["normal-exchange", "closed-reader"] as const) {
      await t.test(`${mode} reaches EOF without retaining either group or generation lease`, async () => {
        await withGateRuntime(async (runtime) => {
          const pair = preparePair(runtime, mode);
          const pending = observed(startPair(runtime, pair));
          // Registration remains in the private log after a short target exits;
          // do not require a live kernel identity for these normal completion cases.
          const enrolled = await Promise.all([
            waitForTrace(runtime, pair.submission.runId, "supervisor_registered"),
            waitForTrace(runtime, pair.interactor.runId, "supervisor_registered"),
          ]);
          const outcome = await bounded(pending, 8_000, `${mode} failed to settle at pipe EOF`);
          assert.ok("value" in outcome, "error" in outcome ? String(outcome.error) : undefined);
          t.diagnostic(`${mode}: ${JSON.stringify(outcome.value)}`);
          assert.equal(outcome.value.runId, pair.runId);
          assert.equal(outcome.value.interactorResult.reason, "exited", JSON.stringify(outcome.value));
          assert.equal(outcome.value.interactorResult.exitCode, 0, JSON.stringify(outcome.value));
          if (mode === "normal-exchange") {
            assert.equal(outcome.value.verdict, "AC", JSON.stringify(outcome.value));
            assert.equal(outcome.value.submissionResult.reason, "exited");
            assert.equal(outcome.value.submissionResult.exitCode, 0);
            assert.ok(outcome.value.submissionResult.stdoutBytes > 0);
            assert.ok(outcome.value.interactorResult.stdoutBytes > 0);
          } else {
            assert.notEqual(outcome.value.submissionResult.reason, "internal_error",
              "an ordinary closed input reader must not become a relay infrastructure failure");
          }
          await provePairDrained(runtime, pair, enrolled);
          await runtime.harness.shutdown();
          await waitForGenerationExclusive(runtime.generationPath, 5_000);
        });
      });
    }
  }

  if (caseSelection === undefined || caseSelection === "resources") {
    for (const side of ["submission", "interactor"] as const) {
      for (const resourceCase of RESOURCE_CASES) {
        await t.test(`${side} ${resourceCase.name} preserves the independent reason and canonical verdict`, async () => {
          await withGateRuntime(async (runtime) => {
            const pair = preparePair(runtime, "resources");
            const actor = pair[side];
            const peer = pair[side === "submission" ? "interactor" : "submission"];
            actor.args = [...resourceCase.args];
            peer.args = [...resourceCase.peerArgs];
            if (resourceCase.name === "nonzero exit" || resourceCase.name === "signal crash") {
              // A checker failure remains authoritative even when the submission
              // already exited nonzero or from a signal: both protocols specify JE.
              if (side === "submission") peer.args = ["drain-then-exit", "3"];
            }
            if (resourceCase.outputBytes !== undefined) actor.limits.outputBytes = resourceCase.outputBytes;
            if (resourceCase.wallTimeMs !== undefined) actor.limits.wallTimeMs = resourceCase.wallTimeMs;
            if (resourceCase.memoryBytes !== undefined) actor.limits.memoryBytes = resourceCase.memoryBytes;
            const pending = observed(startPair(runtime, pair));
            const enrolled = await Promise.all([pair.submission, pair.interactor].map((participant) =>
              waitForTrace(runtime, participant.runId, "supervisor_registered")));
            const outcome = await bounded(pending, 8_000, `${side} ${resourceCase.name} never settled`);
            assert.ok("value" in outcome, "error" in outcome ? String(outcome.error) : undefined);
            const result = outcome.value;
            t.diagnostic(`${side} ${resourceCase.name}: ${JSON.stringify(result)}`);
            const actorResult = side === "submission" ? result.submissionResult : result.interactorResult;
            const peerResult = side === "submission" ? result.interactorResult : result.submissionResult;
            assert.equal(actorResult.reason, resourceCase.reason, JSON.stringify(result));
            if (resourceCase.exitCode !== undefined) {
              assert.equal(actorResult.exitCode, resourceCase.exitCode, JSON.stringify(result));
            }
            if (resourceCase.name === "signal crash") {
              assert.ok(actorResult.signalOrStatus, JSON.stringify(result));
            }
            if (resourceCase.outputBytes !== undefined) {
              assert.ok(actorResult.stdoutBytes > resourceCase.outputBytes, JSON.stringify(result));
              assert.equal(peerResult.reason, "cancelled", JSON.stringify(result));
              assert.equal(peerResult.stdoutBytes, 0, JSON.stringify(result));
            }
            if (resourceCase.wallTimeMs !== undefined || resourceCase.memoryBytes !== undefined) {
              assert.equal(peerResult.reason, "cancelled", JSON.stringify(result));
            }
            assert.equal(result.verdict, side === "submission"
              ? resourceCase.submissionVerdict : resourceCase.interactorVerdict, JSON.stringify(result));
            assert.equal(result.scoreMultiplier, resourceCase.name === "clean exit" ? 1 : 0,
              JSON.stringify(result));
            await provePairDrained(runtime, pair, enrolled);
            await runtime.harness.shutdown();
            await waitForGenerationExclusive(runtime.generationPath, 5_000);
          });
        });
      }
    }

    await t.test("repeated pair cancellation preserves one terminal result and cannot revive either group", async () => {
      await withGateRuntime(async (runtime) => {
        const pair = preparePair(runtime, "exchange-and-hold");
        const pending = observed(startPair(runtime, pair));
        const enrolled = await releasedPair(runtime, pair);
        assert.equal(await cancelRun(runtime, pair.runId), true);
        const outcome = await bounded(pending, 5_000, "cancelled pair retained its terminal result");
        assert.ok("value" in outcome, "error" in outcome ? String(outcome.error) : undefined);
        assert.equal(outcome.value.verdict, "CANCELLED", JSON.stringify(outcome.value));
        assert.equal(outcome.value.scoreMultiplier, 0, JSON.stringify(outcome.value));
        assert.equal(outcome.value.submissionResult.reason, "cancelled", JSON.stringify(outcome.value));
        assert.equal(outcome.value.interactorResult.reason, "cancelled", JSON.stringify(outcome.value));
        await provePairDrained(runtime, pair, enrolled);
        for (const runId of [pair.runId, pair.runId, pair.submission.runId, pair.interactor.runId]) {
          assert.equal(await cancelRun(runtime, runId), false,
            `terminal cancellation resurrected ownership for ${runId}`);
        }
        await provePairDrained(runtime, pair, enrolled);
        await runtime.harness.shutdown();
        await waitForGenerationExclusive(runtime.generationPath, 5_000);
      });
    });
  }
});

function withGateRuntime(operation: (runtime: GateRuntime) => Promise<void>): Promise<void> {
  // This suite intentionally fails and preserves its private runtime on residual
  // processes. Numeric group cleanup must never conceal missing executor pins.
  return withGuardianGateRuntime(async (runtime) => {
    try {
      await operation(runtime);
    } catch (error) {
      // Preserve the authenticated milestones before successful harness teardown
      // removes its disposable directory. This grants no signaling authority.
      logFailureEvidence(runtime);
      throw error;
    }
  }, false);
}

function logFailureEvidence(runtime: GateRuntime): void {
  // Diagnostics only: a recorded number selects read-only rows and is never
  // treated as authority to signal a process or process group.
  console.error("paired lifecycle failure executor stderr:", runtime.harness.stderrDiagnostic);
  try {
    console.error("paired lifecycle failure trace:", fs.readFileSync(runtime.eventLog, "utf8"));
  } catch (error) {
    console.error("paired lifecycle trace read failed:", String(error));
  }
  try {
    const events = readTraceEvents(runtime.eventLog)
      .filter((event) => event.generation === runtime.generation);
    const groups = new Set(events.flatMap((event) => event.anchor ? [event.anchor.pgid] : []));
    const controls = new Set([
      runtime.harness.pid,
      ...events.flatMap((event) => event.guardian ? [event.guardian.pid] : []),
    ]);
    const inventory = spawnSync("/bin/ps",
      ["-ww", "-axo", "pid=,ppid=,pgid=,stat=,wchan=,command="],
      { encoding: "utf8", timeout: 3_000, maxBuffer: 2 * 1024 * 1024 });
    if (inventory.error) throw inventory.error;
    if (inventory.status !== 0) {
      throw new Error(`ps diagnostic failed (${inventory.status}): ${inventory.stderr}`);
    }
    const rows = inventory.stdout.split("\n").map((row) => ({
      row,
      identity: row.match(/^\s*(\d+)\s+(\d+)\s+(\d+)\s+/),
    }));
    console.error("paired lifecycle authenticated PGID inventory (pid ppid pgid stat wchan command):",
      JSON.stringify({ generation: runtime.generation, groups: [...groups],
        rows: rows.filter(({ identity }) => identity !== null && groups.has(Number(identity[3])))
          .map(({ row }) => row.trim()) }));
    console.error("paired lifecycle executor/guardian inventory (pid ppid pgid stat wchan command):",
      JSON.stringify(rows.filter(({ identity }) => identity !== null && controls.has(Number(identity[1])))
        .map(({ row }) => row.trim())));
  } catch (error) {
    // Keep the original failing assertion even when evidence gathering fails.
    console.error("paired lifecycle process diagnostic failed:", String(error));
  }
}

type PairMode = "exchange-and-hold" | "normal-exchange" | "closed-reader" | "resources";

function preparePair(runtime: GateRuntime, mode: PairMode): ExecutorInteractiveRunSpec {
  // Explicitly selected test toolchain; no PATH search or fallback is permitted.
  const compiler = "/usr/bin/clang++";
  assert.ok(fs.existsSync(compiler), "The lifecycle gate requires the explicit /usr/bin/clang++ test compiler.");
  const runId = gateId("interactive");
  const submissionWorkspace = gateId("submission_workspace");
  const interactorWorkspace = gateId("interactor_workspace");
  fs.mkdirSync(path.join(runtime.executorRoot, "workspaces", submissionWorkspace));
  fs.mkdirSync(path.join(runtime.executorRoot, "workspaces", interactorWorkspace));
  const fixtureRoot = path.join(process.cwd(), "server", "test-fixtures", "corpus", "static", "cpp_interactor");
  const resourceSource = fs.readFileSync(path.join(process.cwd(), "server", "security-fixtures", "cpp", "resource_attacks.cpp"), "utf8");
  const artifact = (side: string, source: string): string => {
    const stem = `${runId}-${side}`;
    const sourcePath = path.join(runtime.directory, `${stem}.cpp`);
    const binaryPath = path.join(runtime.executorRoot, "artifacts", stem);
    fs.writeFileSync(sourcePath, source, { mode: 0o600, flag: "wx" });
    const compiled = spawnSync(compiler, ["-std=c++17", "-O0", sourcePath, "-o", binaryPath], {
      encoding: "utf8", timeout: 30_000, maxBuffer: 1024 * 1024,
      // Compilation is trusted test setup outside the sandbox; remove loader injection.
      env: sanitizedExecutorEnvironment({}),
    });
    if (compiled.error) throw compiled.error;
    assert.equal(compiled.status, 0, `test fixture compilation failed: ${compiled.stderr}`);
    fs.chmodSync(binaryPath, 0o500);
    return `artifacts/${stem}`;
  };
  let submissionSource = fs.readFileSync(path.join(fixtureRoot, "solution.cpp"), "utf8");
  let interactorSource = fs.readFileSync(path.join(fixtureRoot, "interactor.cpp"), "utf8");
  if (mode === "exchange-and-hold") {
    const existingSleep = `#define main resourceFixtureMain\n${resourceSource}\n#undef main\n`;
    const hold = `char mode[] = "sleep-ms"; char duration[] = "30000"; char* args[] = {argv[0], mode, duration}; return resourceFixtureMain(3, args);`;
    submissionSource = `${existingSleep}\nint main(int argc, char** argv) { int value; if (!(std::cin >> value) || value != 7) return 65; std::cout << value * 2 << std::endl; std::cerr << "submission-received-7\\n" << std::flush; ${hold} }\n`;
    interactorSource = `${existingSleep}\nint main(int argc, char** argv) { std::cout << 7 << std::endl; int value; if (!(std::cin >> value) || value != 14) return 65; std::cerr << "interactor-received-14\\n" << std::flush; ${hold} }\n`;
  } else if (mode === "resources") {
    // Extend only the test entry point; allocation/output/sleep still call the
    // existing harmless resource fixture. SIGTERM avoids crash core files.
    const source = `#define main resourceFixtureMain\n${resourceSource}\n#undef main\n#include <csignal>\n` +
      `int main(int argc, char** argv) {\n` +
      `    if (argc == 3 && std::string(argv[1]) == "exit-code") return std::atoi(argv[2]);\n` +
      `    if (argc == 3 && std::string(argv[1]) == "delayed-exit") { char bytes[4096]; while (std::cin.read(bytes, sizeof(bytes)) || std::cin.gcount() > 0) {} std::this_thread::sleep_for(std::chrono::milliseconds(50)); return std::atoi(argv[2]); }\n` +
      `    if (argc == 3 && std::string(argv[1]) == "drain-then-exit") { char bytes[4096]; while (std::cin.read(bytes, sizeof(bytes)) || std::cin.gcount() > 0) {} return std::atoi(argv[2]); }\n` +
      `    if (argc >= 2 && std::string(argv[1]) == "signal-crash") { std::raise(SIGTERM); return 70; }\n` +
      `    if (argc >= 2 && std::string(argv[1]) == "drain-input") { std::this_thread::sleep_for(std::chrono::milliseconds(100)); char bytes[4096]; while (std::cin.read(bytes, sizeof(bytes)) || std::cin.gcount() > 0) {} std::this_thread::sleep_for(std::chrono::seconds(5)); return 0; }\n` +
      `    return resourceFixtureMain(argc, argv);\n}\n`;
    submissionSource = source;
    interactorSource = source;
  } else if (mode === "closed-reader") {
    submissionSource = resourceSource;
    // Existing resource fixture emits a bounded 256 KiB while the checker closes stdin.
    interactorSource = "#include <unistd.h>\nint main() { close(STDIN_FILENO); usleep(200000); return 0; }\n";
  }
  const submissionId = artifact("submission", submissionSource);
  const interactorId = artifact("interactor", interactorSource);
  const input = path.join(runtime.executorRoot, "workspaces", interactorWorkspace, "input.txt");
  fs.writeFileSync(input, "7\n", { mode: 0o600, flag: "wx" });
  const participant = (side: string, workspaceId: string, executableId: string,
    role: "submission" | "checker", args: string[]): ExecutorRunSpec => ({
    runId: `${runId}_${side}`, role, workspaceId, executableId, args,
    stdoutFile: "stdout.txt", stderrFile: "stderr.txt", environment: {},
    limits: { wallTimeMs: 60_000, memoryBytes: 128 * 1024 * 1024, processCount: 1,
      threadCount: 64, outputBytes: 1024 * 1024, totalWriteBytes: 4 * 1024 * 1024,
      openFiles: 64, createdFiles: 16 },
  });
  return {
    runId,
    submission: participant("submission", submissionWorkspace, submissionId, "submission",
      mode === "closed-reader" ? ["output-bytes", String(256 * 1024)] : []),
    interactor: participant("interactor", interactorWorkspace, interactorId, "checker",
      mode === "normal-exchange" ? [input] : []),
  };
}

async function startPair(runtime: GateRuntime, spec: ExecutorInteractiveRunSpec): Promise<ExecutorInteractiveRunResult> {
  const response = await runtime.harness.request({ type: "interactive_run", id: crypto.randomUUID(), spec }, 20_000);
  assert.equal(response.type, "interactive_run_result");
  assert.equal(response.result.runId, spec.runId);
  assert.equal(response.result.submissionResult.runId, spec.submission.runId);
  assert.equal(response.result.interactorResult.runId, spec.interactor.runId);
  return response.result;
}

async function releasedPair(runtime: GateRuntime, pair: ExecutorInteractiveRunSpec) {
  const registered = await Promise.all([pair.submission, pair.interactor].map(async (participant) => {
    const registration = await waitForTrace(runtime, participant.runId, "supervisor_registered");
    const committed = await waitForTrace(runtime, participant.runId, "executor_active_committed");
    const go = await waitForTrace(runtime, participant.runId, "guardian_go");
    const target = await waitForTrace(runtime, participant.runId, "target_started");
    assert.ok(registration.lineIndex < committed.lineIndex && committed.lineIndex < go.lineIndex);
    assert.deepEqual(requireIdentity(registration, "anchor"), requireIdentity(target, "anchor"));
    for (const field of ["guardian", "anchor", "target"] as const) {
      assertKernelIdentity(requireIdentity(target, field));
    }
    return target;
  }));
  assert.notEqual(requireIdentity(registered[0], "anchor").pgid, requireIdentity(registered[1], "anchor").pgid);
  // Both sides must be ready before either is released. Each controller emits
  // its own commitment after the pair's readiness barrier.
  const ready = await Promise.all([pair.submission, pair.interactor].map((participant) =>
    waitForTrace(runtime, participant.runId, "supervisor_ready")));
  const releases = await Promise.all([pair.submission, pair.interactor].map((participant) =>
    waitForTrace(runtime, participant.runId, "guardian_go")));
  assert.ok(Math.max(...ready.map((event) => event.lineIndex)) < Math.min(...releases.map((event) => event.lineIndex)));
  await waitForExchange(runtime, pair);
  return registered;
}

async function waitForExchange(runtime: GateRuntime, pair: ExecutorInteractiveRunSpec): Promise<void> {
  const deadline = Date.now() + 3_000;
  do {
    const exchanged = [pair.submission, pair.interactor].every((participant, side) => {
      // The fixture acknowledges the exact received peer value through its
      // separately captured stderr. Anonymous relay captures need no public name.
      const filename = path.join(runtime.executorRoot, "workspaces", participant.workspaceId, participant.stderrFile);
      if (!fs.existsSync(filename)) return false;
      assert.equal(fs.lstatSync(filename).isFile(), true);
      return fs.readFileSync(filename, "utf8") === (side === 0
        ? "submission-received-7\n" : "interactor-received-14\n");
    });
    if (exchanged) return;
    await new Promise<void>((resolve) => setTimeout(resolve, 10));
  } while (Date.now() < deadline);
  assert.fail("both released participants did not finish their harmless stdio exchange");
}

async function provePairDrained(runtime: GateRuntime, pair: ExecutorInteractiveRunSpec,
  enrolled: Awaited<ReturnType<typeof releasedPair>>): Promise<void> {
  await Promise.all([pair.submission, pair.interactor].map(async (participant, side) => {
    await waitForTrace(runtime, participant.runId, "group_drained", 5_000);
    await assertGroupEmpty(requireIdentity(enrolled[side], "anchor").pgid);
    assertNoRunProfileArtifacts(runtime, participant.runId);
    const spools = fs.readdirSync(path.join(runtime.executorRoot, "profiles"))
      .filter((name) => name.startsWith(`${participant.runId}-`) && name.endsWith(".interactive"));
    assert.deepEqual(spools, [], `trusted interactive spool remained for ${participant.runId}`);
  }));
  assertNoRunProfileArtifacts(runtime, pair.runId);
}

function parentPid(pid: number): number {
  const result = spawnSync("/bin/ps", ["-o", "ppid=", "-p", String(pid)], { encoding: "utf8" });
  if (result.error) throw result.error;
  assert.equal(result.status, 0, result.stderr);
  const parent = Number(result.stdout.trim());
  assert.ok(Number.isSafeInteger(parent) && parent > 1);
  return parent;
}

function observed<T>(promise: Promise<T>) {
  // Attach failure handling immediately, including paths where a trace assertion
  // aborts the test before the request reaches its bounded terminal observation.
  return promise.then((value) => ({ ok: true as const, value }),
    (error: unknown) => ({ ok: false as const, error }));
}

async function bounded<T>(promise: Promise<T>, timeoutMs: number, message: string): Promise<T> {
  let timer: NodeJS.Timeout | undefined;
  try {
    return await Promise.race([promise, new Promise<never>((_, reject) => {
      timer = setTimeout(() => reject(new Error(message)), timeoutMs);
    })]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}
